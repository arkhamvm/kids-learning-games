#!/usr/bin/env python3
"""Generate the fallback pronunciation clips for games/alphabet and embed them into the page.

The game prefers the device's British English voice (speechSynthesis). When a device has none,
it plays these clips: every letter name + every example word, synthesized offline with
libespeak-ng (British English, female variant), trimmed and encoded as 32 kbps mono MP3,
stored as base64 between the AUDIO START / AUDIO END markers.

    python3 scripts/alphabet_audio.py

Needs libespeak-ng.so.1 (package libespeak-ng1) and ffmpeg with libmp3lame.
Words are read from the game's ABC table, so re-run it after changing an example word.
"""
import base64
import ctypes
import json
import pathlib
import re
import subprocess
import tempfile
import wave

ROOT = pathlib.Path(__file__).resolve().parent.parent
GAME = ROOT / "games" / "alphabet" / "index.html"
START = "// ===== AUDIO START ====="
END = "// ===== AUDIO END ====="

lib = ctypes.CDLL("libespeak-ng.so.1")
lib.espeak_Initialize.argtypes = [ctypes.c_int, ctypes.c_int, ctypes.c_char_p, ctypes.c_int]
lib.espeak_SetVoiceByName.argtypes = [ctypes.c_char_p]
lib.espeak_SetParameter.argtypes = [ctypes.c_int, ctypes.c_int, ctypes.c_int]
lib.espeak_Synth.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_uint, ctypes.c_int, ctypes.c_uint,
                             ctypes.c_uint, ctypes.c_void_p, ctypes.c_void_p]
RATE = lib.espeak_Initialize(2, 500, None, 0)  # AUDIO_OUTPUT_SYNCHRONOUS
CALLBACK = ctypes.CFUNCTYPE(ctypes.c_int, ctypes.POINTER(ctypes.c_short), ctypes.c_int, ctypes.c_void_p)
_pcm = []


@CALLBACK
def _collect(samples, n, _events):
    if n > 0:
        _pcm.append(ctypes.string_at(samples, n * 2))
    return 0


lib.espeak_SetSynthCallback(_collect)
if lib.espeak_SetVoiceByName(b"en+f3") != 0:  # "en" = British English in espeak-ng
    raise SystemExit("espeak-ng voice en+f3 not found")
lib.espeak_SetParameter(3, 58, 0)  # pitch


def synth(text, speed, ssml=False):
    _pcm.clear()
    lib.espeak_SetParameter(1, speed, 0)  # words per minute
    data = text.encode() + b"\0"
    lib.espeak_Synth(data, len(data), 0, 1, 0, 1 | (0x10 if ssml else 0), None, None)  # UTF-8 (+ SSML)
    lib.espeak_Synchronize()
    return b"".join(_pcm)


def mp3_b64(pcm, tmp):
    wav = pathlib.Path(tmp) / "clip.wav"
    out = pathlib.Path(tmp) / "clip.mp3"
    with wave.open(str(wav), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(pcm)
    trim = ("silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
            "silenceremove=start_periods=1:start_threshold=-45dB,areverse,apad=pad_dur=0.08")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-af", trim, "-ac", "1", "-ar", "22050",
                    "-c:a", "libmp3lame", "-b:a", "32k", "-map_metadata", "-1", "-id3v2_version", "0",
                    "-write_xing", "0", str(out)], check=True)
    return base64.b64encode(out.read_bytes()).decode()


def main():
    html = GAME.read_text(encoding="utf-8")
    rows = re.findall(r"\['([A-Z])', '[^']*', '([a-z ]+)',", html)
    if len(rows) != 26:
        raise SystemExit(f"expected 26 rows in the ABC table, found {len(rows)}")
    clips = {"letters": {}, "words": {}}
    with tempfile.TemporaryDirectory() as tmp:
        for letter, word in rows:
            say_letter = f'<speak><say-as interpret-as="characters">{letter}</say-as></speak>'
            clips["letters"][letter] = mp3_b64(synth(say_letter, 115, ssml=True), tmp)
            clips["words"][letter] = mp3_b64(synth(word, 120), tmp)
    block = (f"{START}\n// generated by scripts/alphabet_audio.py (espeak-ng, en-GB) — do not edit by hand\n"
             f"const CLIPS = {json.dumps(clips, separators=(',', ':'))};\n{END}")
    a, b = html.index(START), html.index(END) + len(END)
    GAME.write_text(html[:a] + block + html[b:], encoding="utf-8")
    size = sum(len(v) for kind in clips.values() for v in kind.values())
    print(f"embedded {len(rows) * 2} clips, {size / 1024:.0f} KB base64")


if __name__ == "__main__":
    main()
